            "import re\n",
            "\n",
            "def donut_sequence_to_json(seq: str) -> dict:\n",
            "    \"\"\"Parse Donut XML-style output back to a Python dict.\"\"\"\n",
            "    result = {}\n",
            "    # Find all top-level tags\n",
            "    pattern = r'<s_(\\w+)>(.*?)</s_\\1>'\n",
            "    for match in re.finditer(pattern, seq, re.DOTALL):\n",
            "        key = match.group(1)\n",
            "        value = match.group(2).strip()\n",
            "        # Check if it's a list (contains <s_el> tags)\n",
            "        if '<s_el>' in value:\n",
            "            items = []\n",
            "            for el_match in re.finditer(r'<s_el>(.*?)</s_el>', value, re.DOTALL):\n",
            "                items.append(donut_sequence_to_json(el_match.group(1)))\n",
            "            result[key] = items\n",
            "        else:\n",
            "            result[key] = value if value else None\n",
            "    return result\n",
            "\n",
            "\n",
            "# Pick a sample image from the training set (they are PNGs now)\n",
