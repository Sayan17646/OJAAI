# 2. Update Step 4 Preprocessing Cell 1
# We find the cell that contains Setup directories
for cell in notebook['cells']:
    if cell['cell_type'] == 'code' and any('Setup directories' in line for line in cell['source']):
        print("Found Step 4 cell 1. Replacing...")
        cell['source'] = [
            "import os\n",
            "import json\n",
            "import re\n",
            "import shutil\n",
            "from pathlib import Path\n",
            "\n",
            "# ── Setup directories ────────────────────────────────────────────────────────\n",
            "TRAIN_DIR = Path(\"/content/donut_train_data\")\n",
            "IMAGES_DIR = TRAIN_DIR / \"images\"\n",
            "TRAIN_DIR.mkdir(parents=True, exist_ok=True)\n",
            "IMAGES_DIR.mkdir(parents=True, exist_ok=True)\n",
            "\n",
            "def parse_header_field(gt_str: str, field_name: str) -> str:\n",
            "    \"\"\"Extract a simple field from the ground truth string using regex.\"\"\"\n",
            "    pattern = rf\"{field_name}:\\s*(.*?)\\s*(?:doctor_name:|clinic_name:|clinic_address:|patient_name:|patient_age:|patient_gender:|date:|medications:|signature:|<\\/s>|$)\"\n",
            "    match = re.search(pattern, gt_str, re.I | re.S)\n",
            "    return match.group(1).strip() if match else \"\"\n",
            "\n",
            "def parse_gt_medications(gt_str: str):\n",
            "    \"\"\"Extract medications list and dosage fields.\"\"\"\n",
            "    meds_match = re.search(\n",
            "        r\"medications:\\s*(.*?)\\s*(?:signature:|date:|doctor_name:|patient_name:|patient_age:|clinic_name:|clinic_address:|<\\/s>)\",\n",
            "        gt_str,\n",
            "        re.S\n",
            "    )\n",
            "    if not meds_match:\n",
            "        return []\n",
            "    meds_block = meds_match.group(1)\n",
            "    items = [item.strip() for item in meds_block.split(\"- \") if item.strip()]\n",
            "\n",
            "    medications = []\n",
            "    i = 0\n",
            "    while i < len(items):\n",
            "        item = items[i]\n",
            "        is_drug = False\n",
            "        match = re.search(r\"(\\d+(?:\\.\\d+)?)\\s*(mg|mcg|ml|g|iu|units?|puffs?|drops?)\\b\", item, re.I)\n",
            "        if match:\n",
            "            is_drug = True\n",
            "        else:\n",
            "            bare_match = re.search(r\"\\b(\\d+)\\b\", item)\n",
            "            if bare_match:\n",
            "                first_word = item.split()[0].lower() if item.split() else \"\"\n",
            "                if first_word not in [\"with\", \"at\", \"after\", \"before\", \"every\", \"once\", \"twice\", \"three\", \"four\", \"take\", \"in\", \"on\"]:\n",
            "                    is_drug = True\n",
            "\n",
            "        if is_drug:\n",
            "            parts = re.split(r\"(\\d+(?:\\.\\d+)?)\\s*(mg|mcg|ml|g|iu|units?|puffs?|drops?)\\b\", item, flags=re.I)\n",
            "            drug_name = parts[0].strip()\n",
            "            dosage_val = float(parts[1]) if len(parts) > 1 else None\n",
            "            dosage_unit = parts[2].lower() if len(parts) > 2 else None\n",
            "\n",
            "            frequency = None\n",
            "            if i + 1 < len(items):\n",
            "                next_item = items[i+1]\n",
            "                next_is_drug = False\n",
            "                if re.search(r\"(\\d+(?:\\.\\d+)?)\\s*(mg|mcg|ml|g|iu|units?|puffs?|drops?)\\b\", next_item, re.I):\n",
            "                    next_is_drug = True\n",
            "\n",
            "                if not next_is_drug:\n",
            "                    frequency = next_item\n",
            "                    i += 1\n",
            "\n",
            "            medications.append({\n",
            "                \"raw_drug_name\": drug_name,\n",
            "                \"dosage_value\": dosage_val,\n",
            "                \"dosage_unit\": dosage_unit,\n",
            "                \"frequency\": frequency\n",
            "            })\n",
            "        i += 1\n",
            "    return medications"
        ]

